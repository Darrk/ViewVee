  String translate(String source) {
    final czech = _translations['cs'] ?? const <String, String>{};
    final key = _keyForSource(source, czech);
    final code = ViewVeeLocaleController.codeOf(locale);
    if (key == null) {
      if (code == 'cs') return source;
      if (code == 'en' && _englishFallback.containsKey(source)) {
        return _englishFallback[source]!;
      }
      final premiumIndex = viewveePremiumSources.indexOf(source);
      final premiumTranslations = viewveePremiumTranslations[code];
      if (premiumIndex >= 0 &&
          premiumTranslations != null &&
          premiumIndex < premiumTranslations.length) {
        return premiumTranslations[premiumIndex];
      }
      final index = viewveeSourceKeys.indexOf(source);
      final translations = _sourceTranslationsFor(code);
      if (index >= 0 && translations != null && index < translations.length) {
        return translations[index];
      }
      return _englishFallback[source] ?? source;
    }
    return _translations[code]?[key] ?? _translations['en']?[key] ?? source;
  }

  static List<String>? _sourceTranslationsFor(String code) =>
      viewveeSourceTranslations1[code] ??
      viewveeSourceTranslations2[code] ??
      viewveeSourceTranslations3[code] ??
      viewveeSourceTranslations4[code] ??
      viewveeSourceTranslations5[code];

  static String? _keyForSource(
    String source, [
    Map<String, String>? czechTranslations,
  ]) {
    final czech =
        czechTranslations ?? _translations['cs'] ?? const <String, String>{};
    return _aliases[source] ??
        czech.entries.where((entry) => entry.value == source).firstOrNull?.key;
  }

