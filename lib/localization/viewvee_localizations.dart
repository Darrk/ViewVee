class ViewVeeLocaleController extends ChangeNotifier {
  ViewVeeLocaleController._();

  static final ViewVeeLocaleController instance = ViewVeeLocaleController._();
  static const preferenceKey = 'preferences.languageCode';

  Locale? _locale;
  Locale? get locale => _locale;

  Future<void> load() async {
    final value = (await SharedPreferences.getInstance()).getString(
      preferenceKey,
    );
    _locale = value == null || value == 'system' ? null : _parse(value);
    notifyListeners();
  }

  Future<void> setLanguage(String code) async {
    _locale = code == 'system' ? null : _parse(code);
    final preferences = await SharedPreferences.getInstance();
    await preferences.setString(preferenceKey, code);
    notifyListeners();
  }

  static Locale _parse(String code) {
    if (code == 'zh_Hant') {
      return const Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hant');
    }
    return Locale(code);
  }

  static String codeOf(Locale locale) =>
      locale.scriptCode == 'Hant' ? 'zh_Hant' : locale.languageCode;

